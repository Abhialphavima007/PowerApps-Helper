'use strict';

const crypto = require('crypto');

const SETUP_ERRORS = Object.freeze({
  WORKFLOW_ADDRESS_INVALID: 'Paste a valid Teams workflow webhook address from its trigger, rather than the flow editor link.',
  WORKFLOW_ADDRESS_UNSUPPORTED: 'Use the HTTPS webhook address generated by a Microsoft Teams workflow.',
  WORKFLOW_SIGNATURE_MISSING: 'This address has no webhook signature. Set Who can trigger the flow to Anyone, save the flow, then copy its newly generated webhook address.',
  WORKFLOW_CHOICES_INVALID: 'Check the work sign-in addresses, Teams group/channel links, notification choices and progress gap (1–1440 minutes).',
  WORKFLOW_DESTINATIONS_MISSING: 'Choose at least one person, group chat or channel before saving this workflow.',
  WORKFLOW_CREDENTIAL_SAVE_FAILED: 'Windows could not securely save the workflow address. Reopen Helper under the same Windows account and try again. Existing credentials were not intentionally removed.',
  WORKFLOW_SETTINGS_SAVE_FAILED: 'The notification settings could not be written. The previous workflow address was restored. Check that Helper can write its app-data folder, then try again.',
  WORKFLOW_RECOVERY_FAILED: 'The notification settings could not be saved and the previous workflow address could not be restored. Workflow reporting has stopped. Reopen Helper and save the matching address and settings again.',
  WORKFLOW_SETUP_FAILED: 'Workflow setup could not be saved. Reopen Helper and try again.'
});

class WorkflowSetupError extends Error {
  constructor(code) { super(SETUP_ERRORS[code]); this.code = code; }
}

function setupError(code) { return new WorkflowSetupError(code); }
function setupFailure(error) {
  // Only our fixed messages cross IPC. OS errors can contain paths or secrets.
  const code = error instanceof WorkflowSetupError && Object.hasOwn(SETUP_ERRORS, error.code)
    ? error.code : 'WORKFLOW_SETUP_FAILED';
  return { ok: false, code, error: SETUP_ERRORS[code] };
}

// A signed callback is a credential. Never include it in errors or status output.
function validateEndpoint(value) {
  if (typeof value !== 'string' || value.length > 8000) throw setupError('WORKFLOW_ADDRESS_INVALID');
  let url;
  try { url = new URL(value.trim()); } catch { throw setupError('WORKFLOW_ADDRESS_INVALID'); }
  const host = url.hostname.toLowerCase();
  const approvedHost = host.endsWith('.logic.azure.com') || host.endsWith('.api.powerplatform.com');
  const invokePath = /\/workflows\/[^/]+\/triggers\/[^/]+\/(?:paths\/)?invoke$/i.test(url.pathname);
  if (url.protocol !== 'https:' || !approvedHost || !invokePath || url.username || url.password || url.port || url.hash ||
      [...url.searchParams.keys()].some(key => /^(?:access_token|token|code)$/i.test(key))) {
    throw setupError('WORKFLOW_ADDRESS_UNSUPPORTED');
  }
  if (!url.searchParams.get('sig')?.trim()) throw setupError('WORKFLOW_SIGNATURE_MISSING');
  return url.href;
}

function routingKey(config, parseChannel, parseGroup) {
  const people = config.recipients.split('; ').filter(Boolean).sort();
  const channel = parseChannel(config.channelLink);
  const group = config.groupLink ? parseGroup(config.groupLink) : null;
  // Preserve existing fixed-workflow hashes when no group is configured.
  return crypto.createHash('sha256').update(JSON.stringify({ people,
    channel: channel ? { teamId: channel.teamId.toLowerCase(), channelId: channel.channelId } : null,
    ...(group ? { group: group.chatId } : {}) })).digest('hex');
}

function envelope(text, helper) {
  const lines = text.split('\n');
  // The Helper flow accepts bounded text-only cards. Keep multi-line details
  // together so a deployment error cannot exceed its TextBlock count limit.
  const blocks = helper ? [lines[0], lines.slice(1).join('\n')].filter(Boolean) : lines;
  return { type: 'message', ...(helper ? { helper } : {}), attachments: [{ contentType: 'application/vnd.microsoft.card.adaptive', contentUrl: null,
    content: { $schema: 'http://adaptivecards.io/schemas/adaptive-card.json', type: 'AdaptiveCard', version: '1.2',
      body: blocks.map((line, index) => ({ type: 'TextBlock', text: line, wrap: true,
        ...(index === 0 ? { weight: 'Bolder', size: 'Medium' } : {}) })) } }] };
}

async function post(url, text, signal, helper) {
  let response;
  try {
    // Anyone webhook authentication uses the signed URL, without a Graph token.
    response = await fetch(validateEndpoint(url), { method: 'POST', redirect: 'error',
      headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(envelope(text, helper)),
      signal: AbortSignal.any([AbortSignal.timeout(15000), signal]) });
  } catch {
    throw new Error('The workflow request did not complete. Delivery is uncertain; check workflow run history before retrying.');
  }
  await response.body?.cancel();
  if (!response.ok) throw new Error(`The Teams workflow returned ${response.status}. Check that it is enabled and its address is current. Delivery has not been confirmed.`);
  // HTTP acceptance is not proof that the subsequent Teams actions succeeded.
}

module.exports = { validateEndpoint, routingKey, envelope, post, setupError, setupFailure };
